// The licences of the Go modules compiled into gosec (plan 9C), for
// deploy/scanner/licenses/GOSEC-THIRD-PARTY.txt. Inputs: the gosec binaries Qualor ships (the
// release binary of install-go.sh, which CI and the toolbox run, and the source build of
// deploy/scanner/Dockerfile's gotools stage). `go version -m` lists each binary's modules;
// `go mod download -json` fetches each through the Go module proxy and checks it against the Go
// checksum database; the module's own licence and notice files are copied. It fails on a module
// whose licence files hold no licence of the allowlist below (MIT, BSD-2/3-Clause, Apache-2.0, ISC).
// Run it where go and the network are available (the toolbox):
//   node tools/analyzers/go-licences.mjs <go> <out> <gosec binary>...
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const LICENCE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;

/** The `mod` and `dep` lines of `go version -m` (not a `(devel)` main module), a `=>` line replacing the dependency above it. */
export function parseBuildInfo(text) {
  const out = [];
  for (const line of text.split('\n')) {
    const cells = line.split('\t');
    // A build's main module is `(devel)`: the image's build module (qualor.dev/go-tools/gosec, Qualor's own),
    // or gosec itself in a build from its own source; gosec's licence is GOSEC-LICENSE.txt.
    if (
      (cells[1] === 'mod' || cells[1] === 'dep') &&
      cells[2] &&
      cells[3] &&
      cells[3] !== '(devel)'
    ) {
      out.push({ path: cells[2], version: cells[3] });
    } else if (cells[1] === '=>' && cells[2] && cells[3] && out.length > 0) {
      out[out.length - 1] = { path: cells[2], version: cells[3] };
    }
  }
  return out;
}

/** The permissive licence a licence text is, or null. */
export function classify(text) {
  if (/Apache License/.test(text) && /Version 2\.0/.test(text)) return 'Apache-2.0';
  if (/Permission is hereby granted, free of charge/.test(text)) return 'MIT';
  if (/Redistribution and use in source and binary forms/.test(text)) {
    return /Neither the name|names of (its|the) contributors/i.test(text)
      ? 'BSD-3-Clause'
      : 'BSD-2-Clause';
  }
  if (/Permission to use, copy, modify, and\/or distribute this software/.test(text)) return 'ISC';
  return null;
}

function main([go, out, ...binaries]) {
  if (!go || !out || binaries.length === 0) {
    throw new Error('usage: node tools/analyzers/go-licences.mjs <go> <out> <gosec binary>...');
  }
  const modules = new Map();
  for (const bin of binaries) {
    for (const m of parseBuildInfo(
      execFileSync(go, ['version', '-m', bin], { encoding: 'utf8' }),
    )) {
      modules.set(`${m.path}@${m.version}`, m);
    }
  }
  const env = {
    ...process.env,
    GOFLAGS: '-mod=mod',
    GOTOOLCHAIN: 'local',
    GOPRIVATE: '',
    GONOSUMDB: '',
  };
  const sections = [];
  const sorted = [...modules.values()].sort((a, b) =>
    a.path === b.path ? (a.version < b.version ? -1 : 1) : a.path < b.path ? -1 : 1,
  );
  for (const m of sorted) {
    const info = JSON.parse(
      execFileSync(go, ['mod', 'download', '-json', `${m.path}@${m.version}`], {
        env,
        encoding: 'utf8',
        cwd: os.tmpdir(),
      }),
    );
    if (typeof info.Dir !== 'string')
      throw new Error(`${m.path}@${m.version}: ${info.Error ?? 'not downloaded'}`);
    const files = readdirSync(info.Dir)
      .filter((f) => LICENCE_FILE.test(f))
      .sort();
    const texts = files.map((f) => readFileSync(path.join(info.Dir, f), 'utf8'));
    const licence = texts.map(classify).find((l) => l !== null);
    if (licence === undefined) {
      throw new Error(
        `${m.path}@${m.version}: no allowed licence in ${files.join(', ') || 'no licence file'}`,
      );
    }
    const body = files.map((f, i) => `---- ${f} ----\n\n${texts[i].trimEnd()}\n`).join('\n');
    sections.push(`${'='.repeat(78)}\n${m.path}@${m.version} (${licence})\n\n${body}`);
  }
  const head =
    'Third-party software compiled into gosec (/opt/qualor/bin/gosec of qualor/scanner, and the\n' +
    'release binary CI runs): the Go modules `go version -m` lists for each build, each with its own\n' +
    'licence and notice files at that version, fetched through the Go module proxy and checked\n' +
    'against the Go checksum database by `go mod download`. Generated by\n' +
    'tools/analyzers/go-licences.mjs; regenerate on every GOSEC_VERSION bump.\n\n';
  writeFileSync(out, head + sections.join('\n'));
  process.stdout.write(`${sections.length} modules -> ${out}\n`);
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main(process.argv.slice(2));
}
