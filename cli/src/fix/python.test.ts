describe('the Python adapter: package managers and verify', () => {
  const direct = () =>
    committed({
      'pyproject.toml': uvProject(['qf-a>=1.2.5']),
      'uv.lock': uvLock(['qf-a'], uvPackage('qf-a', '1.2.5')),
    });

  it('F36: uv finds no solution for the target: no_fix unresolvable', async () => {
    const stderr = [
      'Using CPython 3.12.11',
      '  × No solution found when resolving dependencies:',
      '  ╰─▶ Because only qf-a<=1.2.5 is available and your project depends on',
      "      qf-a>=1.2.6, we can conclude that your project's requirements are",
      '      unsatisfiable.',
    ].join('\n');

    const r = await fix(direct(), QF_A, [failed('uv', 1, stderr)]);

    expect(r.outcome).toEqual({
      noFix: {
        reason: 'unresolvable',
        message: expect.stringMatching(/^`uv` exited with 1: .*No solution found/s) as unknown,
      },
    });
  });

  it('F36: Poetry finds no version for the target: no_fix unresolvable', async () => {
    const dir = committed({
      'pyproject.toml': poetryProject(['qf-a = "^1.2.5"']),
      'poetry.lock': poetryLock(poetryPackage('qf-a', '1.2.5')),
    });
    const stderr =
      "Because app depends on qf-a (^1.2.6) which doesn't match any versions, version solving failed.\n";

    const r = await fix(dir, QF_A, [poetryVersion('2.1.1'), failed('poetry', 1, stderr)]);

    expect(r.outcome).toEqual({
      noFix: {
        reason: 'unresolvable',
        message: expect.stringContaining('`poetry` exited with 1') as unknown,
      },
    });
  });

  it('a solver failure that does not name the package is failure package_manager', async () => {
    const stderr = [
      '  × No solution found when resolving dependencies:',
      '  ╰─▶ Because the current Python version (3.10.4) does not satisfy Python>=3.11',
      '      and qf-z==2.0.0 depends on Python>=3.11, we can conclude that qf-z==2.0.0',
      '      cannot be used.',
    ].join('\n');

    const r = await fix(direct(), QF_A, [failed('uv', 1, stderr)]);

    expect(r.outcome).toEqual({
      failure: {
        code: 'package_manager',
        message: expect.stringContaining('`uv` exited with 1') as unknown,
      },
    });
  });

  it('a failing uv is failure package_manager with its stderr; the files stay as they were', async () => {
    const r = await fix(direct(), QF_A, [
      failed('uv', 2, 'error: Failed to fetch: `https://pypi.org/simple/qf-a/`\n'),
    ]);

    expect(r.outcome).toEqual({
      failure: {
        code: 'package_manager',
        message: '`uv` exited with 2: error: Failed to fetch: `https://pypi.org/simple/qf-a/`',
      },
    });
  });

  it('verify: a lockfile that still resolves the vulnerable version is verify_failed', async () => {
    const r = await fix(direct(), QF_A, [{ tool: 'uv' }]);

    expect(r.outcome).toEqual({
      failure: {
        code: 'verify_failed',
        message: expect.stringContaining(
          'uv.lock still resolves qf-a 1.2.5, below 1.2.6',
        ) as unknown,
      },
    });
  });

  it('verify: a version pushed off its release line (qf-a>=1.2.6 resolving 2.0.1) is no_fix several_lines', async () => {
    const r = await fix(direct(), QF_A, [uvWrites(uvLock(['qf-a'], uvPackage('qf-a', '2.0.1')))]);

    expect(r.outcome).toEqual({
      noFix: {
        reason: 'several_lines',
        message: expect.stringContaining(
          'uv.lock moved qf-a 1.2.5 off its release line 1.x',
        ) as unknown,
      },
    });
  });
});
