// ─── Lockfiles ──────────────────────────────────────────────────────────────

const FILES = 'https://files.pythonhosted.org/packages/ab/cd';
const SHA = (c: string) => 'sha256:' + c.repeat(64);

const uvDependencies = (deps: readonly string[]) =>
  deps.length === 0
    ? []
    : ['dependencies = [', ...deps.map((d) => '    { name = "' + d + '" },'), ']'];

/** A PyPI package of a `uv.lock`, as uv 0.10 writes it. */
function uvPackage(name: string, version: string, deps: readonly string[] = []): string[] {
  const file = FILES + '/' + name.replaceAll('-', '_') + '-' + version;
  return [
    '',
    '[[package]]',
    `name = "${name}"`,
    `version = "${version}"`,
    'source = { registry = "https://pypi.org/simple" }',
    ...uvDependencies(deps),
    `sdist = { url = "${file}.tar.gz", hash = "${SHA('a')}", size = 100 }`,
    'wheels = [',
    `    { url = "${file}-py3-none-any.whl", hash = "${SHA('b')}", size = 90 },`,
    ']',
  ];
}

/** A `uv.lock` of the project `app` (depending on `root`) and the given packages. */
function uvLock(root: readonly string[], ...packages: string[][]): string {
  const app = ['[[package]]', 'name = "app"', 'version = "0.1.0"', 'source = { virtual = "." }'];
  const head = ['version = 1', 'revision = 3', 'requires-python = ">=3.11"', ''];
  return [...head, ...app, ...uvDependencies(root), ...packages.flat(), ''].join('\n');
}

/** A PyPI package of a `poetry.lock` (Poetry 2.1); `name` is TOML basic-string text. */
function poetryPackage(name: string, version: string, deps = ''): string[] {
  const file = name.replaceAll('-', '_') + '-' + version;
  return [
    '',
    '[[package]]',
    `name = "${name}"`,
    `version = "${version}"`,
    'description = ""',
    'optional = false',
    'python-versions = ">=3.8"',
    'files = [',
    `    {file = "${file}-py3-none-any.whl", hash = "${SHA('c')}"},`,
    `    {file = "${name}-${version}.tar.gz", hash = "${SHA('d')}"},`,
    ']',
    ...(deps === '' ? [] : ['', '[package.dependencies]', deps]),
  ];
}

function poetryLock(...packages: string[][]): string {
  return [
    '# This file is automatically @generated by Poetry 2.1.1 and should not be changed by hand.',
    ...packages.flat(),
    '',
    '[metadata]',
    'lock-version = "2.1"',
    'python-versions = "^3.11"',
    'content-hash = "abc"',
    '',
  ].join('\n');
}

// ─── Manifests ──────────────────────────────────────────────────────────────

/** A uv project whose `dependencies` hold `deps`, with comments around them (§11.3). */
function uvProject(deps: string[], tail = ''): string {
  return [
    '# The app.',
    '[project]',
    'name = "app"',
    'version = "0.1.0"',
    'requires-python = ">=3.11"',
    'dependencies = [ # web',
    ...deps.map((d) => `    "${d}",`),
    ']',
    '',
    '[dependency-groups]',
    'dev = ["pytest>=8"]  # tests',
    tail,
  ].join('\n');
}

/** A Poetry project whose `[tool.poetry.dependencies]` hold `deps` after `python`. */
function poetryProject(deps: string[]): string {
  return [
    '[tool.poetry]',
    'name = "app"',
    'version = "0.1.0"',
    'description = ""',
    '',
    '[tool.poetry.dependencies]',
    'python = "^3.11"',
    ...deps,
    '',
    '[tool.poetry.group.dev.dependencies]',
    'pytest = "^8.0" # tests',
    '',
    '[build-system]',
    'requires = ["poetry-core>=2.0.0"]',
    'build-backend = "poetry.core.masonry.api"',
    '',
  ].join('\n');
}

