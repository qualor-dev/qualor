describe('pep508WithTarget', () => {
  it.each([
    ['qf-a>=1.2.5', 'qf-a>=1.2.6'],
    ['qf-a==1.2.5', 'qf-a==1.2.6'],
    ['qf-a~=1.2.5', 'qf-a~=1.2.6'],
    ['qf-a >= 1.2.5', 'qf-a >= 1.2.6'],
    [
      'qf-a[speed]>=1.2.5 ; python_version >= "3.11"',
      'qf-a[speed]>=1.2.6 ; python_version >= "3.11"',
    ],
    ['qf-a (>=1.2.5,<2.0.0)', 'qf-a (>=1.2.6,<2.0.0)'],
    ['qf-a>=1.2.5, <2', 'qf-a>=1.2.6, <2'],
  ])('%s → %s (the operator, extras, marker and upper bound kept)', (req, next) => {
    expect(pep508WithTarget(req, '1.2.6')).toBe(next);
  });

  it.each([
    'qf-a',
    'qf-a<1.3',
    'qf-a>1.2.5',
    'qf-a!=1.2.4',
    'qf-a===1.2.5',
    'qf-a==1.2.*',
    'qf-a==1.2.5,<2',
    'qf-a>=1.2.5,<1.2.6',
    'qf-a>=1.0,>=1.2',
    'qf-a @ https://files.example/qf_a-1.2.5-py3-none-any.whl',
  ])('%s → null (left to a person)', (req) => {
    expect(pep508WithTarget(req, '1.2.6')).toBeNull();
  });

  it('refuses a ~= target with one release number, and a target that is no version', () => {
    expect(pep508WithTarget('qf-a~=1.2', '2')).toBeNull();
    expect(pep508WithTarget('qf-a>=1.2.5', '1.2.6"')).toBeNull();
  });
});

describe('poetryConstraintWithTarget', () => {
  it.each([
    ['^1.2.5', '^1.2.6'],
    ['~1.2.5', '~1.2.6'],
    ['>=1.2.5', '>=1.2.6'],
    ['==1.2.5', '==1.2.6'],
    ['1.2.5', '1.2.6'],
    [' ^ 1.2.5 ', ' ^ 1.2.6 '],
  ])('%s → %s', (constraint, next) => {
    expect(poetryConstraintWithTarget(constraint, '1.2.6')).toBe(next);
  });

  it.each(['*', '~=1.2.5', '>=1.2.5,<2', '<1.3', '^1.2 || ^2.0', '!=1.2.4', '1.2.*', ''])(
    '%j → null',
    (constraint) => {
      expect(poetryConstraintWithTarget(constraint, '1.2.6')).toBeNull();
    },
  );
});

