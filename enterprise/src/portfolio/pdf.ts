/** 4E-2 §3: the project list of the PDF holds at most this many rows. */
export const PDF_PROJECTS_MAX = 50;
/** 4E-2 §3: the render budget, as in 4E-1. */
const RENDER_BUDGET_MS = 60_000;
const CELL_MAX = 120;
/** The font size of the chart axis labels. */
const LABEL = 6.5;
/** Without `vuln.priority` the overview's exploited list is null and nothing about it shows. */
const prioritised = (overview: PortfolioOverview): boolean => overview.attention.exploited !== null;
const RATINGS = ['A', 'B', 'C', 'D', 'E'] as const;
const GATE: Record<string, string> = {
  passed: 'Passed',
  failed: 'Failed',
  error: 'Error',
  none: 'No gate',
};

/** 50000 as "50 000". */
const grouped = (n: number): string => String(n).replace(/\B(?=(\d{3})+$)/g, ' ');
const count = (n: number | null | undefined): string =>
  n === null || n === undefined ? '—' : grouped(n);
const percent = (n: number | null): string => (n === null ? '—' : `${n.toFixed(1)}%`);
const share = (n: number | null): string => percent(n === null ? null : n * 100);
const plural = (n: number, one: string, many: string): string =>
  `${grouped(n)} ${n === 1 ? one : many}`;
const capitalised = (text: string): string => text.charAt(0).toUpperCase() + text.slice(1);
const time = (iso: string): string => `${iso.slice(0, 10)} ${iso.slice(11, 19)} UTC`;
const lastAnalysis = (iso: string | null): string => (iso ? iso.slice(0, 10) : 'Never analysed');
/** A trend point's label: the week's Monday, or the month. */
const period = (start: string, granularity: Granularity): string =>
  granularity === 'week' ? start.slice(0, 10) : start.slice(0, 7);
const projectName = (r: PortfolioProjectRow): string =>
  cut(`${r.project.name} (${r.project.key})`, CELL_MAX);

function scopeName(overview: PortfolioOverview): string {
  const { organization } = overview.scope;
  return organization ? `${organization.name} (${organization.key})` : 'All organisations';
}

/** The columns after a name column that takes what the fixed ones leave. */
function columns(layout: Layout, name: string, fixed: Column[]): Column[] {
  const used = fixed.reduce((sum, c) => sum + c.width, 0);
  return [{ header: name, width: layout.width - used }, ...fixed];
}

const right = (header: string, width: number): Column => ({ header, width, align: 'right' });

function cover(layout: Layout, overview: PortfolioOverview, options: RenderOptions): void {
  const { totals } = overview;
  layout.page();
  layout.doc.moveDown(4);
  layout.heading('Qualor portfolio report', SIZE.title);
  const projects = plural(totals.projects, 'project', 'projects');
  layout.text(
    overview.scope.organization
      ? `Organisation ${scopeName(overview)}: ${projects}, each on its main branch`
      : `All organisations: ${projects} in ` +
          `${plural(overview.organizations?.length ?? 0, 'organisation', 'organisations')}, ` +
          'each on its main branch',
  );
  layout.doc.moveDown(1);
  layout.fields([
    ['Generated', time(overview.generatedAt)],
    ['Generated by', options.generatedBy],
    ['Server version', options.serverVersion],
    [
      'Trend',
      overview.granularity === 'week'
        ? 'Weekly (ISO weeks from Monday 00:00 UTC)'
        : 'Monthly (calendar months, UTC)',
    ],
  ]);
  layout.text(
    'The figures cover only the projects that the user who generated this report can read.',
    COLOR.muted,
  );
}

/** Label and value cards, four to a row. */
function cards(layout: Layout, items: readonly (readonly [string, string])[]): void {
  const { doc } = layout;
  const left = doc.page.margins.left;
  const perRow = 4;
  const gap = 8;
  const width = (layout.width - gap * (perRow - 1)) / perRow;
  const height = 44;
  for (let i = 0; i < items.length; i += perRow) {
    if (doc.y + height > doc.page.height - doc.page.margins.bottom) layout.page();
    const y = doc.y;
    for (const [j, [label, value]] of items.slice(i, i + perRow).entries()) {
      const x = left + j * (width + gap);
      doc.rect(x, y, width, height).lineWidth(0.5).strokeColor(COLOR.rule).stroke();
      doc.font('body').fontSize(SIZE.margin).fillColor(COLOR.muted);
      doc.text(label, x + 6, y + 6, { width: width - 12, lineBreak: false, features: FEATURES });
      doc.font('bold').fontSize(SIZE.heading).fillColor(COLOR.text);
      doc.text(value, x + 6, y + 19, { width: width - 12, lineBreak: false, features: FEATURES });
    }
    doc.x = left;
    doc.y = y + height + gap;
  }
  doc.moveDown(0.3);
}

async function totals(layout: Layout, overview: PortfolioOverview): Promise<void> {
  const t = overview.totals;
  layout.page();
  layout.heading('Totals');
  cards(layout, [
    ['Projects', count(t.projects)],
    ['Analysed', count(t.analysed)],
    ['Abandoned', count(t.abandoned)],
    ['Quality gate passed', share(t.passedShare)],
    ['Lines of code', count(t.ncloc)],
    ['Coverage', percent(t.coverage)],
    ['Duplication', percent(t.duplication)],
    ['Open issues', count(t.issues)],
    ['Blocker', count(t.bySeverity.blocker)],
    ['High', count(t.bySeverity.high)],
    ['Secrets', count(t.secrets)],
    ['Vulnerable dependencies', count(t.vulnerableDependencies)],
    ['Vulnerable releases', count(t.vulnerableReleases)],
    ...(prioritised(overview) ? [['Exploited vulnerabilities', count(t.exploited)] as const] : []),
  ]);
  layout.text(
    'Coverage and duplication are weighted by lines of code. The quality gate share is of the ' +
      'analysed projects.',
    COLOR.muted,
  );
  layout.heading('Quality gates', SIZE.subheading);
  await layout.table(
    [
      right('Passed', layout.width / 4),
      right('Failed', layout.width / 4),
      right('Error', layout.width / 4),
      right('No gate', layout.width / 4),
    ],
    [[count(t.gate.passed), count(t.gate.failed), count(t.gate.error), count(t.gate.none)]],
  );
  layout.heading('Ratings', SIZE.subheading);
  const ratingColumn = (layout.width - 120) / RATINGS.length;
  await layout.table(
    [{ header: 'Projects rated', width: 120 }, ...RATINGS.map((r) => right(r, ratingColumn))],
    [
      ['Security', ...RATINGS.map((r) => count(t.securityRating[r]))],
      ['Reliability', ...RATINGS.map((r) => count(t.reliabilityRating[r]))],
    ],
  );
  layout.fields([
    ['Security issues', count(t.securityIssues)],
    ['Reliability issues', count(t.reliabilityIssues)],
    ['Maintainability issues', count(t.maintainabilityIssues)],
    ['New issues', count(t.newIssues)],
  ]);
}

/** The multiple of 2, 4, 6, 8 or 10 times a power of ten at or above `max`, so ticks are round. */
function roundedTop(max: number): number {
  if (max <= 0) return 2;
  const power = 10 ** Math.floor(Math.log10(max));
  return ([2, 4, 6, 8].find((m) => m * power >= max) ?? 10) * power;
}

interface Series {
  title: string;
  values: (number | null)[];
  range: [number, number];
  tick: (n: number) => string;
}

/** A line chart drawn as vector paths: grid lines with values, the line, dots, period labels. */
function chart(layout: Layout, series: Series, labels: readonly string[]): void {
  const { doc } = layout;
  const left = doc.page.margins.left;
  const axis = 44;
  const height = 84;
  if (doc.y + SIZE.subheading * 2.5 + height + 24 > doc.page.height - doc.page.margins.bottom) {
    layout.page();
  }
  doc.moveDown(0.6);
  doc.font('bold').fontSize(SIZE.subheading).fillColor(COLOR.text);
  doc.text(series.title, left, doc.y, { width: layout.width, features: FEATURES });
  const step = labels.length > 1 ? (layout.width - axis - 20) / (labels.length - 1) : 0;
  // 20 points on the right leave room for half of the last label.
  const box = { x: left + axis, y: doc.y + 6, w: layout.width - axis - 20, h: height };
  const [min, max] = series.range;
  doc.font('body').fontSize(LABEL);
  for (const tick of [min, (min + max) / 2, max]) {
    const y = box.y + box.h - ((tick - min) / (max - min)) * box.h;
    doc
      .moveTo(box.x, y)
      .lineTo(box.x + box.w, y)
      .lineWidth(0.5)
      .strokeColor(COLOR.rule)
      .stroke();
    doc.fillColor(COLOR.muted);
    doc.text(series.tick(tick), left, y - LABEL / 2 - 1, {
      width: axis - 6,
      align: 'right',
      lineBreak: false,
      features: FEATURES,
    });
  }
  doc
    .moveTo(box.x, box.y)
    .lineTo(box.x, box.y + box.h)
    .lineTo(box.x + box.w, box.y + box.h)
    .lineWidth(0.75)
    .strokeColor(COLOR.muted)
    .stroke();
  const { path, dots } = lineChartPaths(series.values, box, series.range);
  if (path) doc.path(path).lineWidth(1.25).strokeColor(COLOR.text).stroke();
  for (const dot of dots) doc.circle(dot.x, dot.y, 1.75).fill(COLOR.text);
  const width = step || box.w;
  doc.fillColor(COLOR.muted);
  for (const [i, label] of labels.entries()) {
    const x = labels.length > 1 ? box.x + i * step : box.x + box.w / 2;
    doc.text(label, x - width / 2, box.y + box.h + 4, {
      width,
      align: 'center',
      lineBreak: false,
      features: FEATURES,
    });
  }
  doc.x = left;
  doc.y = box.y + box.h + 4 + LABEL + 8;
}

async function trend(layout: Layout, overview: PortfolioOverview): Promise<void> {
  const points = overview.trend;
  const labels = points.map((p) => period(p.start, overview.granularity));
  const unit = overview.granularity === 'week' ? 'week' : 'month';
  layout.page();
  layout.heading('Trend');
  const periods = plural(points.length, unit, `${unit}s`);
  layout.text(
    `${periods}, oldest first. Each point is the state at the ` +
      `end of its ${unit}; the last is the current ${unit}, up to ${time(overview.generatedAt)}.`,
    COLOR.muted,
  );
  const percentTicks = (n: number): string => `${n}%`;
  const top = (values: number[]): [number, number] => [0, roundedTop(Math.max(0, ...values))];
  const series: Series[] = [
    {
      title: 'Quality gate passed',
      values: points.map((p) => (p.passedShare === null ? null : p.passedShare * 100)),
      range: [0, 100],
      tick: percentTicks,
    },
    {
      title: 'Coverage',
      values: points.map((p) => p.coverage),
      range: [0, 100],
      tick: percentTicks,
    },
    {
      title: 'Lines of code',
      values: points.map((p) => p.ncloc),
      range: top(points.map((p) => p.ncloc)),
      tick: grouped,
    },
    {
      title: 'Open issues',
      values: points.map((p) => p.issues),
      range: top(points.map((p) => p.issues)),
      tick: grouped,
    },
  ];
  for (const s of series) chart(layout, s, labels);

  const periodColumn: Column = { header: capitalised(unit), width: 60 };
  const quality = [
    'Projects',
    'Analysed',
    'Abandoned',
    'Gate passed',
    'Coverage',
    'Duplication',
    'Lines of code',
    'Issues',
  ];
  layout.heading('Quality by period', SIZE.subheading);
  await layout.table(
    [periodColumn, ...quality.map((h) => right(h, (layout.width - 60) / quality.length))],
    points.map((p) => [
      period(p.start, overview.granularity),
      count(p.projects),
      count(p.analysed),
      count(p.abandoned),
      share(p.passedShare),
      percent(p.coverage),
      percent(p.duplication),
      count(p.ncloc),
      count(p.issues),
    ]),
  );
  const findings = ['Blocker', 'High', 'Medium', 'Low', 'Info', 'New issues', 'Analyses', 'Triage'];
  layout.heading('Findings and activity by period', SIZE.subheading);
  await layout.table(
    [periodColumn, ...findings.map((h) => right(h, (layout.width - 60) / findings.length))],
    points.map((p) => [
      period(p.start, overview.granularity),
      count(p.bySeverity.blocker),
      count(p.bySeverity.high),
      count(p.bySeverity.medium),
      count(p.bySeverity.low),
      count(p.bySeverity.info),
      count(p.newIssues),
      count(p.analyses),
      count(p.triage),
    ]),
  );
  layout.text(
    'Analyses: succeeded analyses of any branch uploaded in the period. Triage: findings marked ' +
      "false positive or won't fix in the period.",
    COLOR.muted,
  );
}

async function organizations(layout: Layout, overview: PortfolioOverview): Promise<void> {
  if (!overview.organizations) return;
  layout.page();
  layout.heading('Organisations');
  const aggregateCells = (a: PortfolioAggregate): string[] => [
    count(a.projects),
    count(a.analysed),
    count(a.abandoned),
    share(a.passedShare),
    count(a.ncloc),
    percent(a.coverage),
    percent(a.duplication),
    count(a.issues),
    count(a.bySeverity.blocker),
    count(a.bySeverity.high),
  ];
  await layout.table(
    columns(layout, 'Organisation', [
      right('Projects', 40),
      right('Analysed', 44),
      right('Abandoned', 50),
      right('Gate passed', 44),
      right('Lines of code', 44),
      right('Coverage', 44),
      right('Duplication', 50),
      right('Issues', 34),
      right('Blocker', 38),
      right('High', 30),
    ]),
    overview.organizations.map((o) => [
      cut(`${o.name} (${o.key})`, CELL_MAX),
      ...aggregateCells(o),
    ]),
  );
}

async function attention(layout: Layout, overview: PortfolioOverview): Promise<void> {
  const all = overview.scope.kind === 'all';
  const exploited = overview.attention.exploited;
  const list = [
    ...(exploited
      ? ([
          [
            'Exploited vulnerabilities',
            'Projects with an open vulnerability that is exploited in the wild, most first.',
            'exploited',
          ],
        ] as const)
      : []),
    ['Failing quality gates', 'Sorted by blocker and high findings.', 'failingGates'],
    ['Worst security ratings', 'Projects rated B to E, worst first.', 'worstSecurity'],
    ['Most blocker and high findings', 'Projects with at least one, most first.', 'mostSevere'],
    [
      'Abandoned projects',
      'No succeeded main-branch analysis in the last 30 days, or never analysed.',
      'abandoned',
    ],
  ] as const;
  layout.page();
  layout.heading('Projects that need attention');
  for (const [title, note, key] of list) {
    layout.heading(title, SIZE.subheading);
    layout.text(note, COLOR.muted);
    const rows = overview.attention[key] ?? [];
    const exploitedList = key === 'exploited';
    if (rows.length === 0) {
      layout.text('None.');
      continue;
    }
    await layout.table(
      columns(layout, 'Project', [
        ...(all ? [{ header: 'Organisation', width: 70 }] : []),
        { header: 'Gate', width: 36 },
        right('Security', 38),
        right('Reliability', 44),
        right('Blocker', 38),
        right('High', 30),
        right('Issues', 34),
        right('Last analysis', 56),
        ...(exploitedList ? [right('Exploited', 44)] : []),
      ]),
      rows.map((r) => [
        projectName(r),
        ...(all ? [cut(r.organization.name, CELL_MAX)] : []),
        r.gate === null ? '—' : (GATE[r.gate] ?? r.gate),
        r.securityRating ?? '—',
        r.reliabilityRating ?? '—',
        count(r.bySeverity?.blocker),
        count(r.bySeverity?.high),
        count(r.issues),
        lastAnalysis(r.lastAnalysisAt),
        ...(exploitedList ? [count(r.exploited)] : []),
      ]),
    );
  }
}

async function projects(
  layout: Layout,
  overview: PortfolioOverview,
  rows: readonly PortfolioProjectRow[],
): Promise<void> {
  const all = overview.scope.kind === 'all';
  const total = Math.max(overview.totals.projects, rows.length);
  const shown = Math.min(rows.length, PDF_PROJECTS_MAX);
  layout.page();
  layout.heading('Projects');
  layout.text(
    shown < total
      ? `The first ${shown} of ${plural(total, 'project', 'projects')}, by quality gate, then ` +
          'security rating.'
      : `${plural(total, 'project', 'projects')}, by quality gate, then security rating.`,
  );
  if (shown > 0) {
    await layout.table(
      columns(layout, 'Project', [
        ...(all ? [{ header: 'Organisation', width: 64 }] : []),
        { header: 'Last analysis', width: 50 },
        { header: 'Gate', width: 34 },
        right('Security', 38),
        right('Reliability', 44),
        right('Lines of code', 40),
        right('Coverage', 44),
        right('Issues', 34),
        right('Blocker', 38),
        right('High', 30),
      ]),
      rows
        .slice(0, shown)
        .map((r) => [
          projectName(r),
          ...(all ? [cut(r.organization.name, CELL_MAX)] : []),
          lastAnalysis(r.lastAnalysisAt),
          r.gate === null ? '—' : (GATE[r.gate] ?? r.gate),
          r.securityRating ?? '—',
          r.reliabilityRating ?? '—',
          count(r.ncloc),
          percent(r.coverage),
          count(r.issues),
          count(r.bySeverity?.blocker),
          count(r.bySeverity?.high),
        ]),
    );
  }
  if (shown < total) layout.text('The CSV export lists every project.');
}

/** Most first, nulls last. */
const byCountDesc = (a: number | null, b: number | null): number => (b ?? -1) - (a ?? -1);

/**
 * Plan 5 R4: the projects with a vulnerable release, or with `vuln.priority` an exploited
 * vulnerability: exploited first, then vulnerable releases, then project key.
 */
async function vulnerableProjects(
  layout: Layout,
  overview: PortfolioOverview,
  candidates: readonly PortfolioProjectRow[],
): Promise<void> {
  const all = overview.scope.kind === 'all';
  const withPriority = prioritised(overview);
  const listed = candidates
    .filter((r) => (r.vulnerableReleases ?? 0) > 0 || (withPriority && (r.exploited ?? 0) > 0))
    .sort(
      (a, b) =>
        (withPriority ? byCountDesc(a.exploited, b.exploited) : 0) ||
        byCountDesc(a.vulnerableReleases, b.vulnerableReleases) ||
        (a.project.key < b.project.key ? -1 : a.project.key > b.project.key ? 1 : 0),
    );
  const shown = listed.slice(0, PDF_PROJECTS_MAX);
  layout.page();
  layout.heading('Projects with vulnerable releases');
  if (shown.length === 0) {
    layout.text('No project has a vulnerable release.');
    return;
  }
  await layout.table(
    columns(layout, 'Project', [
      ...(all ? [{ header: 'Organisation', width: 120 }] : []),
      right('Vulnerable releases', 80),
      ...(withPriority ? [right('Exploited', 60)] : []),
    ]),
    shown.map((r) => [
      projectName(r),
      ...(all ? [cut(r.organization.name, CELL_MAX)] : []),
      count(r.vulnerableReleases),
      ...(withPriority ? [count(r.exploited)] : []),
    ]),
  );
  if (listed.length > shown.length) {
    layout.text(
      `…and ${grouped(listed.length - shown.length)} more. The CSV export lists every project.`,
    );
  }
}

interface RenderOptions {
  generatedBy: string;
  serverVersion: string;
  /** Every project with a vulnerable release or an exploited vulnerability; `rows` without it. */
  vulnerable?: readonly PortfolioProjectRow[];
  deadline?: number;
  fontsDir?: string;
}

/**
 * 4E-2 §3: the portfolio as an A4 PDF on 4E-1's layout: cover, totals, trend with four line
 * charts, organisations (all scope), attention lists, and the first 50 of `rows`. The caller
 * supplies `rows` sorted by gate, then security rating (`projects(sort: 'gate')`), as the PDF
 * says; they are printed in the order given. The footer id and the creation date are
 * `generatedAt`, so one input renders to the same bytes.
 */
export async function renderPortfolioPdf(
  overview: PortfolioOverview,
  rows: PortfolioProjectRow[],
  options: RenderOptions,
): Promise<Buffer> {
  const deadline = options.deadline ?? Date.now() + RENDER_BUDGET_MS;
  const due = (): void => {
    if (Date.now() > deadline) throw new RenderTimeoutError();
  };
  const scope = scopeName(overview);
  const { doc, done } = createDocument({
    title: 'Qualor portfolio report',
    author: options.generatedBy,
    subject: `Portfolio of ${scope}, generated ${overview.generatedAt}`,
    date: new Date(overview.generatedAt),
    fontsDir: options.fontsDir,
  });
  const layout = new Layout(doc, deadline);
  const sections = [
    () => cover(layout, overview, options),
    () => totals(layout, overview),
    () => trend(layout, overview),
    () => organizations(layout, overview),
    () => attention(layout, overview),
    () => projects(layout, overview, rows),
    () => vulnerableProjects(layout, overview, options.vulnerable ?? rows),
  ];
  for (const section of sections) {
    due();
    await section();
  }
  layout.frame(cut(`Qualor portfolio · ${scope}`, CELL_MAX), overview.generatedAt);
  doc.end();
  return done;
}
